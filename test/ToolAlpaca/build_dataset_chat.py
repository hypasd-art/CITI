import copy
def process(datas):
    processed_data = []
    for data in datas:
        # processed = {}
        # print(data)
        assert len(data["process"]) % 2 == 0
        history = []
        for i in range(0, len(data["process"]), 2):
            processed = {}
            chat_input = data["process"][i]
            output = data["process"][i+1][1]
            assert data["process"][i][0] == "observation" or data["process"][i][0] == "user"
            assert data["process"][i+1][0] == 'assistant'

            processed["system"] = default_system
            processed['tools'] = data["tools"][1]
            processed['input'] = chat_input
            processed['output'] = output
            processed['history'] = copy.deepcopy(history)
            history.append([data["process"][i], data["process"][i+1]])
            processed_data.append(processed)
    return processed_data

